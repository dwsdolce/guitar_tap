@pytest.mark.parametrize("fixture", FIXTURES)
def test_report_matches_the_expected_lines(fixture, tmp_path):
    with open(os.path.join(TESTS, fixture + ".guitartap"), "rb") as f:
        measurement = reports.measurements_from_json(f.read())[0]
    path = str(tmp_path / "report.pdf")
    reports.export_report_for_measurement(measurement, path)

    date = squeezed([format_display_datetime(measurement.timestamp)])
    actual = [
        (page, baseline,
         "<date>" if squeezed([text]) == date else "<generated>" if text.startswith("Generated by") else text)
        for page, baseline, text in lines_of(path)
    ]
    with open(os.path.join(TESTS, fixture + ".guitartap.pdf.txt"), encoding="utf-8") as f:
        expected = []
        for row in f.read().splitlines():
            page, baseline, text = row.split("\t", 2)
            expected.append((int(page), float(baseline), text))
    listing = (f"{fixture}:\n--- actual\n" + "\n".join(map(show, actual))
               + "\n--- expected\n" + "\n".join(map(show, expected)))
    assert len(actual) == len(expected), f"line count {len(actual)} != {len(expected)}\n{listing}"
    for a, e in zip(actual, expected):
        assert (a[0] == e[0] and abs(a[1] - e[1]) <= 1 and squeezed([a[2]]) == squeezed([e[2]])), (
            f"{show(a)} != expected {show(e)}\n{listing}")
