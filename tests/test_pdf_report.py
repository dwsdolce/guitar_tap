"""A saved measurement's PDF report, as the measurement list exports it (export_report_for_measurement),
read back line by line and compared with the expected lines beside its fixture (``<fixture>.pdf.txt``):
each line's page, its height on the page and its words. A line's height is its baseline's distance from the
page's top — for a line mixing sizes, the baseline of its largest text — and must be within 1 pt of the
expected. Words are compared with whitespace removed. The measurement's date and the "Generated by …" line
are matched by position only (they depend on the locale, the time and the build). The expected lines are
Swift's; Swift PDFReportTests and the web suite have the same cases and the same expected files.
"""

